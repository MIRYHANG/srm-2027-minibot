int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC1_Init();
  MX_SPI1_Init();
  /* USER CODE BEGIN 2 */
  HAL_Delay(NRF_POWERUP_MS);
  radio_ready = NrfLink_Configure(nRF24_MODE_TX);

  uint32_t last_send = HAL_GetTick();
  uint8_t counter = 0U;
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    if (radio_ready && (uint32_t)(HAL_GetTick() - last_send) >= LINK_TEST_PERIOD)
    {
      last_send += LINK_TEST_PERIOD;

      uint8_t buf[1] = {counter};
      counter++;

      switch (NrfLink_Send(buf, (uint8_t)sizeof(buf), NULL, NULL))
      {
        case NRF_TX_OK:
          tx_ok_count++;
          HAL_GPIO_TogglePin(LED_STATUS1_GPIO_Port, LED_STATUS1_Pin);
          break;
        case NRF_TX_LOST:
          tx_lost_count++;
          break;
        default:
          tx_timeout_count++;
          break;
      }
    }
  }
  /* USER CODE END 3 */
}

